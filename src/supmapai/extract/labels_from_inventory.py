"""Create a human-editable map label sheet from an inventory manifest."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

LABEL_COLUMNS = [
    "map_dir",
    "canonical_name",
    "version",
    "duplicate_group",
    "quality_tier",
    "size_x",
    "size_z",
    "player_count",
    "has_scmap",
    "has_scenario_lua",
    "has_save_lua",
    "has_preview",
    "primary_modes",
    "secondary_modes",
    "pace",
    "lane_structure",
    "expansion_pattern",
    "symmetry",
    "team_layout",
    "spawn_roles",
    "mex_pattern",
    "hydro_pattern",
    "reclaim_pattern",
    "biome",
    "visual_style",
    "readability",
    "notes",
]


def _has_files(map_record: dict, key: str) -> bool:
    return bool(map_record.get(key, []))


def _row_from_map_record(map_record: dict) -> dict[str, str]:
    row = {column: "" for column in LABEL_COLUMNS}
    row["map_dir"] = map_record.get("map_dir", "")
    row["has_scmap"] = str(_has_files(map_record, "scmap")).lower()
    row["has_scenario_lua"] = str(_has_files(map_record, "scenario_lua")).lower()
    row["has_save_lua"] = str(_has_files(map_record, "save_lua")).lower()
    row["has_preview"] = str(_has_files(map_record, "preview_images")).lower()
    return row


def build_label_rows(inventory: dict) -> list[dict[str, str]]:
    rows = [_row_from_map_record(map_record) for map_record in inventory.get("maps", [])]
    rows.sort(key=lambda row: row["map_dir"].lower())
    return rows


def write_label_sheet(rows: list[dict[str, str]], out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=LABEL_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create a spreadsheet-friendly map label CSV from an inventory JSON."
    )
    parser.add_argument(
        "--inventory",
        required=True,
        type=Path,
        help="Inventory JSON generated by supmapai.extract.inventory.",
    )
    parser.add_argument(
        "--out",
        required=True,
        type=Path,
        help="Output CSV path, for example data\\labels\\map_labels.csv.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    inventory = json.loads(args.inventory.read_text(encoding="utf-8"))
    rows = build_label_rows(inventory)
    write_label_sheet(rows, args.out)
    print(f"Wrote {len(rows)} label row(s) to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
