import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {initialState,calibrationStatus,selectMap,batchFor,suggestion,questions,defaultAnswers,defaultConfiguration,isComplete,vaultPreview,uniqueSuggestions} from '../src/lib/survey.ts';
const maps=JSON.parse(readFileSync(new URL('../src/data/review-maps.json',import.meta.url)));
const state=initialState(maps);
assert.equal(state.settings.anchors.length,6);
assert.ok(state.settings.anchors.every(a=>maps.some(m=>m.id===a.mapId)));
assert.equal(new Set(maps.map(m=>m.id)).size,maps.length);
assert.equal(maps.filter(m=>m.priority).length,429);
assert.equal(selectMap(maps,state,[],false,'priority').id,state.settings.anchors[0].mapId);
assert.equal(calibrationStatus(state).referenceReady,false);
for(const a of state.settings.anchors) state.submissions.push({mapId:a.mapId,phase:'calibration',scaleVersion:5,calibrationRevision:'initial',answers:{quality:'unknown'},configuration:'4v4',setup:'default'});
assert.equal(calibrationStatus(state).completed,6);
assert.equal(calibrationStatus(state).status,'Awaiting expert references');
for(const a of state.settings.anchors){a.configuration='4v4';a.setup='default';a.reference={land:{min:2,max:3},navy:{min:2,max:3},air:{min:2,max:3}};}
assert.equal(calibrationStatus(state).status,'Insufficient evidence');
state.submissions.forEach(s=>s.answers={land:0,navy:0,air:0});
assert.equal(calibrationStatus(state).status,'Review recommended');
state.submissions.forEach(s=>s.answers={land:2,navy:3,air:2});
assert.equal(calibrationStatus(state).status,'No flag detected');
const first=selectMap(maps,state,[],false,'priority');assert.ok(first.priority);
state.submissions.push({mapId:first.id,phase:'collection',answers:{land:0}});
assert.notEqual(selectMap(maps,state,[],false,'priority').id,first.id);
assert.notEqual(selectMap(maps,state,[first.id],true,'all').id,first.id);
const only=maps.find(m=>!m.priority);state.settings.priorityIds=[only.id];
assert.equal(selectMap(maps,state,[],true,'priority').id,only.id);
assert.equal(selectMap(maps,state,[only.id],true,'priority'),undefined);
assert.equal(batchFor(first,[],false).length,17);
assert.equal(batchFor(first,[],true).length,17);
assert.equal(suggestion({...first,waterPercent:0,mexCount:0,playerCount:2,texturePack:''})[0].label,'Mostly dry');
assert.equal(suggestion({...first,waterPercent:null,mexCount:null,texturePack:''}).length,0);
state.settings.revision='new';assert.equal(calibrationStatus(state).completed,0);
console.log('Passed: catalog identity, six anchors, calibration gates/flags/unknowns, priority selection, skips, partial batches, missing/zero suggestions, reference revisions.');

assert.deepEqual(questions.map(q=>q.id),['unique','quality','beauty','land','air','navy','pressure','midCombat','lateCombat','eco','open','expansion','drops','build','readable','gameReadability','roles']);
assert.ok(questions.every(q=>q.labels.length===5));
assert.deepEqual(batchFor(first,[],false),batchFor(only,state.submissions,true));
assert.ok(Object.values(defaultAnswers()).every(v=>v==='unknown'));
assert.equal(defaultConfiguration({...first,playerCount:8}),'4v4');
assert.equal(defaultConfiguration({...first,playerCount:7}),'3v4');
assert.equal(defaultConfiguration({...first,playerCount:null}),'Unknown / preview only');
assert.equal(isComplete(defaultAnswers(),[]),false);
const full=Object.fromEntries(questions.map(q=>[q.id,3]));
assert.equal(isComplete(full,['Forest']),true);
assert.equal(isComplete(full,[]),false);
assert.equal(isComplete({...full,quality:'unknown'},['Forest']),false);
assert.ok(vaultPreview({...first,previewUrl:'/local.webp'}).startsWith('https://content.faforever.com/'));
assert.ok(uniqueSuggestions({...first,mapDir:'adaptive_example',waterPercent:80}).includes('Water-rich terrain'));
console.log('Passed: exact fixed question order, uniqueness rating, five-point scales, unknown defaults, default teams, completion colors, vault URLs, trait suggestions.');
